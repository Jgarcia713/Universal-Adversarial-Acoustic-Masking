import random
from pathlib import Path

import numpy as np
import librosa
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers

from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report

SEED = 42
random.seed(SEED)
np.random.seed(SEED)
tf.random.set_seed(SEED)

DATA_DIR = Path("../input-sounds/cropped_base_pretraining")

CLASSES = list("abcdefghijklmnopqrstuvwxyz")
CLASS_TO_IDX = {key: i for i, key in enumerate(CLASSES)}

SAMPLE_RATE = 44100
N_SAMPLES = 11025
N_FFT = 1024
HOP_LENGTH = 225
N_MELS = 64

print("TensorFlow:", tf.__version__)

waveforms = []
labels = []
filenames = []

for key in CLASSES:
    for i in range(1, 126):
        path = DATA_DIR / f"{key}_{i}.wav"

        if not path.exists():
            continue

        audio, sr = librosa.load(path, sr=None, mono=True)

        if sr != SAMPLE_RATE:
            audio = librosa.resample(
                audio, orig_sr=sr, target_sr=SAMPLE_RATE
            )

        if len(audio) < N_SAMPLES:
            audio = np.pad(audio, (0, N_SAMPLES - len(audio)))
        else:
            audio = audio[:N_SAMPLES]

        waveforms.append(audio.astype(np.float32))
        labels.append(CLASS_TO_IDX[key])
        filenames.append(str(path))

waveforms = np.stack(waveforms)
labels = np.array(labels, dtype=np.int32)
filenames = np.array(filenames)

print("Waveforms:", waveforms.shape)
print("Labels:", labels.shape)
print("Number of classes:", len(np.unique(labels)))

indices = np.arange(len(labels))

train_idx, temp_idx = train_test_split(
    indices,
    test_size=0.30,
    random_state=SEED,
    stratify=labels
)

val_idx, test_idx = train_test_split(
    temp_idx,
    test_size=0.50,
    random_state=SEED,
    stratify=labels[temp_idx]
)

print("Train:", len(train_idx))
print("Validation:", len(val_idx))
print("Test:", len(test_idx))


def extract_features(audio):
    mel = librosa.feature.melspectrogram(
        y=audio,
        sr=SAMPLE_RATE,
        n_fft=N_FFT,
        hop_length=HOP_LENGTH,
        n_mels=N_MELS,
        pad_mode="constant"
    )

    log_mel = librosa.power_to_db(mel, ref=np.max)

    return log_mel.astype(np.float32)


X = np.stack([
    extract_features(audio)
    for audio in waveforms
])

X = X[..., np.newaxis]

print("Features:", X.shape)


"""## Fitting the CNN"""



def build_cnn():
    model = keras.Sequential([
        keras.Input(shape=(64, 50, 1)),

        layers.Conv2D(32, (3, 3), activation="relu"),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),

        layers.Conv2D(64, (3, 3), activation="relu"),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(0.2),

        layers.Conv2D(128, (3, 3), activation="relu"),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(0.3),

        layers.Flatten(),

        layers.Dense(128, activation="relu"),
        layers.BatchNormalization(),
        layers.Dropout(0.4),

        layers.Dense(len(CLASSES), activation="softmax")
    ])

    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=1e-3),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )

    return model


model = build_cnn()
model.summary()

callbacks = [
    keras.callbacks.EarlyStopping(
        monitor="val_loss",
        patience=5,
        restore_best_weights=True
    ),

    keras.callbacks.ModelCheckpoint(
        "keystroke_cnn_best.keras",
        monitor="val_loss",
        save_best_only=True
    )
]

history = model.fit(
    X[train_idx],
    labels[train_idx],

    validation_data=(
        X[val_idx],
        labels[val_idx]
    ),

    epochs=30,
    batch_size=32,
    callbacks=callbacks,
    verbose=1
)


test_loss, test_acc = model.evaluate(
    X[test_idx],
    labels[test_idx],
    verbose=0
)

print(f"Test accuracy: {test_acc:.2%}")

predictions = model.predict(X[test_idx], verbose=0)
predicted_labels = np.argmax(predictions, axis=1)

print(classification_report(
    labels[test_idx],
    predicted_labels,
    target_names=CLASSES,
    zero_division=0
))

import json

model.save("../artifacts/models/keystroke_cnn.keras")

np.savez_compressed(
    "../artifacts/models/keystroke_dataset.npz",
    waveforms=waveforms,
    labels=labels,
    filenames=filenames,
    train_idx=train_idx,
    val_idx=val_idx,
    test_idx=test_idx
)

config = {
    "classes": CLASSES,
    "sample_rate": SAMPLE_RATE,
    "n_samples": N_SAMPLES,
    "n_fft": N_FFT,
    "hop_length": HOP_LENGTH,
    "n_mels": N_MELS,
    "feature_type": "librosa log-mel power spectrogram",
    "db_reference": "per-sample maximum",
    "input_shape": [64, 50, 1]
}

with open("../artifacts/models/preprocessing_config.json", "w") as f:
    json.dump(config, f, indent=2)

print("Saved model, dataset, and preprocessing configuration.")
